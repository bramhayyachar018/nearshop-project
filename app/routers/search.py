from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session
from sqlalchemy import func
from typing import List, Optional
from .. import models, schemas
from ..database import get_db
from ..utils import standard_response

router = APIRouter(
    prefix="/search",
    tags=["search"]
)

@router.get("/", response_model=dict)
def search_products(
    query: str = Query(None, description="Text to search in product names/categories"),
    lat: Optional[float] = Query(None, description="User latitude for nearby search"),
    lng: Optional[float] = Query(None, description="User longitude for nearby search"),
    page: int = Query(1, ge=1),
    size: int = Query(20, ge=1, le=100),
    db: Session = Depends(get_db)
):
    """
    Search products by text and optionally sort/filter by proximity to user.
    Uses basic ilike filtering. For pgvector, a different route/logic is needed depending on the query embedding.
    """
    offset = (page - 1) * size

    # Base query for inventory that joins product and store
    base_query = db.query(models.Inventory).join(models.Product).join(models.Store)

    # Filter by text if provided
    if query:
        search_pattern = f"%{query}%"
        base_query = base_query.filter(
            (models.Product.name.ilike(search_pattern)) |
            (models.Product.category.ilike(search_pattern))
        )

    # Only return items in stock
    base_query = base_query.filter(models.Inventory.quantity > 0)

    total = base_query.count()

    # If spatial ordering is required (simple Euclidean approximation or use PostGIS if available)
    if lat is not None and lng is not None:
        # Simple distance squared approximation: (lat-lat2)^2 + (lng-lng2)^2
        # For a real app, integrate PostGIS or use Haversine formula in Postgres.
        distance_expr = func.power(models.Store.latitude - lat, 2) + func.power(models.Store.longitude - lng, 2)
        base_query = base_query.order_by(distance_expr.asc())

    items = base_query.offset(offset).limit(size).all()

    results = []
    for item in items:
        results.append(
            schemas.SearchResultOut(
                product=schemas.ProductOut.model_validate(item.product),
                store_id=item.store_id,
                quantity=item.quantity
            )
        )

    pagination = schemas.PaginatedResponse(
        items=results,
        total=total,
        page=page,
        size=size
    )

    return standard_response(success=True, data=pagination.model_dump())

@router.post("/semantic", response_model=dict)
def semantic_search(
    embedding: List[float],
    page: int = Query(1, ge=1),
    size: int = Query(20, ge=1, le=100),
    db: Session = Depends(get_db)
):
    """
    Search products by semantic similarity using pgvector.
    Requires passing the query embedding generated by the client/backend ML model.
    """
    offset = (page - 1) * size

    # We use L2 distance (cosine distance '<=>' is also popular for embeddings)
    # distance = models.Product.embedding.l2_distance(embedding)
    # In pgvector-sqlalchemy, you can order by embedding distance

    products = db.query(models.Product).order_by(
        models.Product.embedding.l2_distance(embedding)
    ).offset(offset).limit(size).all()

    total = db.query(models.Product).count() # Approximate total or remove if slow

    results = [schemas.ProductOut.model_validate(p) for p in products]

    pagination = schemas.PaginatedResponse(
        items=results,
        total=total,
        page=page,
        size=size
    )

    return standard_response(success=True, data=pagination.model_dump())
